// RUN: llvm-mc -triple ia64 -show-encoding %s | FileCheck %s

// The forms GNU as takes with an operand left out. A compare or a test that
// names one predicate to set has p0 for the other, before the pseudo-op is
// made the instruction it stands for, so one that exchanges its targets sets
// the second. A move to the predicates with no mask is a move to all of them.
// The encodings are those GNU as produces.

// CHECK: cmp.eq p6, p0 = r1, r2 // encoding: [0x80,0x21,0x20,0x00,0xc0,0x01]
	cmp.eq p6 = r1, r2
// CHECK: cmp.lt p6, p0 = r1, r2 // encoding: [0x80,0x21,0x20,0x00,0x80,0x01]
	cmp.lt p6 = r1, r2
// CHECK: cmp.eq p0, p6 = r1, r2 // encoding: [0x00,0x20,0x20,0x30,0xc0,0x01]
	cmp.ne p6 = r1, r2
// CHECK: cmp.lt p0, p6 = 1, r2 // encoding: [0x00,0x20,0x20,0x30,0x88,0x01]
	cmp.ge p6 = 1, r2
// CHECK: cmp.ltu p6, p0 = r2, r1 // encoding: [0x80,0x41,0x10,0x00,0xa0,0x01]
	cmp.gtu p6 = r1, r2
// CHECK: cmp.eq.unc p6, p0 = r1, r2 // encoding: [0x80,0x31,0x20,0x00,0xc0,0x01]
	cmp.eq.unc p6 = r1, r2
// CHECK: cmp.eq.and p6, p0 = r1, r2 // encoding: [0x80,0x21,0x20,0x00,0x82,0x01]
	cmp.eq.and p6 = r1, r2
// CHECK: cmp.ne.or.andcm p6, p0 = r1, r2 // encoding: [0x80,0x31,0x20,0x00,0xc2,0x01]
	cmp.ne.or.andcm p6 = r1, r2
// CHECK: cmp4.ltu p0, p6 = r2, r1 // encoding: [0x00,0x40,0x10,0x30,0xa4,0x01]
	cmp4.leu p6 = r1, r2
// CHECK: cmp4.lt.unc p6, p0 = 5, r2 // encoding: [0x80,0xb1,0x20,0x00,0x8c,0x01]
	cmp4.lt.unc p6 = 5, r2
// CHECK: tbit.z p6, p0 = r1, 3 // encoding: [0x80,0xc1,0x10,0x00,0xa0,0x00]
	tbit.z p6 = r1, 3
// CHECK: tbit.z.unc p0, p6 = r1, 3 // encoding: [0x00,0xd0,0x10,0x30,0xa0,0x00]
	tbit.nz.unc p6 = r1, 3
// CHECK: tbit.nz.or p6, p0 = r1, 3 // encoding: [0x80,0xd1,0x10,0x00,0xa2,0x00]
	tbit.nz.or p6 = r1, 3
// CHECK: tnat.z p6, p0 = r1 // encoding: [0x80,0x21,0x10,0x00,0xa0,0x00]
	tnat.z p6 = r1
// CHECK: tnat.nz.and p6, p0 = r1 // encoding: [0x80,0x31,0x10,0x00,0xb0,0x00]
	tnat.nz.and p6 = r1
// CHECK: tf.z p6, p0 = 33 // encoding: [0x80,0x61,0x08,0x00,0xa0,0x00]
	tf.z p6 = 33
// CHECK: tf.z.unc p0, p6 = 33 // encoding: [0x00,0x70,0x08,0x30,0xa0,0x00]
	tf.nz.unc p6 = 33
// CHECK: fcmp.lt p6, p0 = f6, f7 // encoding: [0x80,0xc1,0x70,0x00,0x90,0x00]
	fcmp.lt p6 = f6, f7
// CHECK: fcmp.lt.unc.s1 p0, p6 = f6, f7 // encoding: [0x00,0xd0,0x70,0x30,0x94,0x00]
	fcmp.nlt.unc.s1 p6 = f6, f7
// CHECK: fcmp.lt p6, p0 = f7, f6 // encoding: [0x80,0xe1,0x60,0x00,0x90,0x00]
	fcmp.gt p6 = f6, f7
// CHECK: fclass.m p6, p0 = f6, 256 // encoding: [0x80,0xc1,0x00,0x04,0xa0,0x00]
	fclass.m p6 = f6, 0x100
// CHECK: fclass.m.unc p0, p6 = f6, 256 // encoding: [0x00,0xd0,0x00,0x34,0xa0,0x00]
	fclass.nm.unc p6 = f6, 0x100
// CHECK: mov pr = r4, -2 // encoding: [0xc0,0x9f,0x00,0xff,0x16,0x00]
	mov pr = r4
// CHECK: (p7) mov pr = r4, -2 // encoding: [0xc7,0x9f,0x00,0xff,0x16,0x00]
	(p7) mov pr = r4
