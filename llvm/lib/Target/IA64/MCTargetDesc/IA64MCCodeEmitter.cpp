// This file implements the IA64MCCodeEmitter class.
//
// An IA-64 instruction is a 41-bit slot; three of them and a 5-bit template
// make a 128-bit bundle. The emitter encodes one slot at a time, in the low
// 41 bits of six little-endian bytes, and leaves it to the streamer to pack
// slots into bundles.
//
//===----------------------------------------------------------------------===//

#include "MCTargetDesc/IA64BaseInfo.h"
#include "MCTargetDesc/IA64MCTargetDesc.h"
#include "llvm/ADT/SmallVector.h"
#include "llvm/MC/MCCodeEmitter.h"
#include "llvm/MC/MCContext.h"
#include "llvm/MC/MCExpr.h"
#include "llvm/MC/MCInst.h"
#include "llvm/MC/MCInstrInfo.h"
#include "llvm/MC/MCRegisterInfo.h"
#include "llvm/MC/MCSubtargetInfo.h"
#include "llvm/Support/ErrorHandling.h"

using namespace llvm;

#define DEBUG_TYPE "mccodeemitter"

namespace {

class IA64MCCodeEmitter : public MCCodeEmitter {
  MCContext &Ctx;

public:
  IA64MCCodeEmitter(const MCInstrInfo &, MCContext &Ctx) : Ctx(Ctx) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  uint64_t getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  uint64_t getImmMinus1OpValue(const MCInst &MI, unsigned OpNo,
                               SmallVectorImpl<MCFixup> &Fixups,
                               const MCSubtargetInfo &STI) const;

  template <int64_t N>
  uint64_t getReversedImmOpValue(const MCInst &MI, unsigned OpNo,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const {
    return static_cast<uint64_t>(N - MI.getOperand(OpNo).getImm());
  }

  uint64_t getPmpyshrCountOpValue(const MCInst &MI, unsigned OpNo,
                                  SmallVectorImpl<MCFixup> &Fixups,
                                  const MCSubtargetInfo &STI) const;

  uint64_t getPCRelOpValue(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const;

  uint64_t getInc3OpValue(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          const MCSubtargetInfo &STI) const;

  uint64_t encodeAllocFrame(const MCInst &MI, uint64_t Insn,
                            const MCSubtargetInfo &STI) const;
};

} // end anonymous namespace

void IA64MCCodeEmitter::encodeInstruction(const MCInst &MI,
                                          SmallVectorImpl<char> &CB,
                                          SmallVectorImpl<MCFixup> &Fixups,
                                          const MCSubtargetInfo &STI) const {
  uint64_t Slot = getBinaryCodeForInstr(MI, Fixups, STI);
  for (unsigned I = 0; I != IA64::SlotBytes; ++I)
    CB.push_back(static_cast<char>(Slot >> (8 * I)));
}

uint64_t
IA64MCCodeEmitter::getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                                     SmallVectorImpl<MCFixup> &Fixups,
                                     const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<uint64_t>(MO.getImm());
  llvm_unreachable("unhandled operand kind");
}

uint64_t
IA64MCCodeEmitter::getImmMinus1OpValue(const MCInst &MI, unsigned OpNo,
                                       SmallVectorImpl<MCFixup> &Fixups,
                                       const MCSubtargetInfo &STI) const {
  return static_cast<uint64_t>(MI.getOperand(OpNo).getImm() - 1);
}

uint64_t
IA64MCCodeEmitter::getPmpyshrCountOpValue(const MCInst &MI, unsigned OpNo,
                                          SmallVectorImpl<MCFixup> &Fixups,
                                          const MCSubtargetInfo &STI) const {
  switch (MI.getOperand(OpNo).getImm()) {
  case 0:
    return 0;
  case 7:
    return 1;
  case 15:
    return 2;
  case 16:
    return 3;
  }
  llvm_unreachable("invalid pmpyshr2 count");
}

uint64_t IA64MCCodeEmitter::getPCRelOpValue(const MCInst &MI, unsigned OpNo,
                                            SmallVectorImpl<MCFixup> &Fixups,
                                            const MCSubtargetInfo &STI) const {
  // The operand is a displacement in bytes between bundles.
  return static_cast<uint64_t>(MI.getOperand(OpNo).getImm() >> 4);
}

uint64_t IA64MCCodeEmitter::getInc3OpValue(const MCInst &MI, unsigned OpNo,
                                           SmallVectorImpl<MCFixup> &Fixups,
                                           const MCSubtargetInfo &STI) const {
  // A sign and the magnitude: 16, 8, 4 and 1 are 0 to 3.
  int64_t Inc = MI.getOperand(OpNo).getImm();
  uint64_t Sign = Inc < 0 ? 4 : 0;
  switch (Inc < 0 ? -Inc : Inc) {
  case 16:
    return Sign | 0;
  case 8:
    return Sign | 1;
  case 4:
    return Sign | 2;
  case 1:
    return Sign | 3;
  }
  llvm_unreachable("invalid fetchadd increment");
}

uint64_t IA64MCCodeEmitter::encodeAllocFrame(const MCInst &MI, uint64_t Insn,
                                             const MCSubtargetInfo &STI) const {
  // The operands after the destination are the numbers of input, local,
  // output and rotating registers.
  uint64_t Inputs = MI.getOperand(1).getImm();
  uint64_t Locals = MI.getOperand(2).getImm();
  uint64_t Outputs = MI.getOperand(3).getImm();
  uint64_t Rotating = MI.getOperand(4).getImm();
  uint64_t Sol = Inputs + Locals;
  uint64_t Sof = Sol + Outputs;
  assert(Sof <= IA64II::MaxFrameSize && Rotating % 8 == 0 && Rotating <= Sof &&
         "invalid register stack frame");
  return Insn | (Rotating / 8) << 27 | Sol << 20 | Sof << 13;
}

#include "IA64GenMCCodeEmitter.inc"

MCCodeEmitter *llvm::createIA64MCCodeEmitter(const MCInstrInfo &MCII,
                                             MCContext &Ctx) {
  return new IA64MCCodeEmitter(MCII, Ctx);
}
