#define DEBUG_TYPE "mccodeemitter"

namespace {

class IA64MCCodeEmitter : public MCCodeEmitter {
  const MCInstrInfo &MCII;
  MCContext &Ctx;

public:
  IA64MCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx)
      : MCII(MCII), Ctx(Ctx) {}

  void encodeInstruction(const MCInst &MI, SmallVectorImpl<char> &CB,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  uint64_t getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  uint64_t getImmMinus1OpValue(const MCInst &MI, unsigned OpNo,
                               SmallVectorImpl<MCFixup> &Fixups,
                               const MCSubtargetInfo &STI) const;

  template <int64_t N>
  uint64_t getReversedImmOpValue(const MCInst &MI, unsigned OpNo,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const {
    return static_cast<uint64_t>(N - MI.getOperand(OpNo).getImm());
  }

  uint64_t getStrideOpValue(const MCInst &MI, unsigned OpNo,
                            SmallVectorImpl<MCFixup> &Fixups,
                            const MCSubtargetInfo &STI) const {
    return static_cast<uint64_t>(MI.getOperand(OpNo).getImm() >> 6) & 0x1f;
  }

  uint64_t getPmpyshrCountOpValue(const MCInst &MI, unsigned OpNo,
                                  SmallVectorImpl<MCFixup> &Fixups,
                                  const MCSubtargetInfo &STI) const;

  /// An immediate, or an expression for a fixup of kind \p Kind.
  template <unsigned Kind>
  uint64_t getExprOpValue(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          const MCSubtargetInfo &STI) const {
    const MCOperand &MO = MI.getOperand(OpNo);
    if (MO.isImm())
      return static_cast<uint64_t>(MO.getImm());
    Fixups.push_back(MCFixup::create(0, MO.getExpr(), Kind));
    return 0;
  }

  /// An IP-relative target: a displacement in bytes between bundles, or an
  /// expression for the fixup \p Kind.
  template <unsigned Kind>
  uint64_t getPCRelOpValue(const MCInst &MI, unsigned OpNo,
                           SmallVectorImpl<MCFixup> &Fixups,
                           const MCSubtargetInfo &STI) const {
    const MCOperand &MO = MI.getOperand(OpNo);
    if (MO.isImm())
      return static_cast<uint64_t>(MO.getImm() >> 4);
    Fixups.push_back(MCFixup::create(0, MO.getExpr(), Kind, /*PCRel=*/true));
    return 0;
  }

  uint64_t getInc3OpValue(const MCInst &MI, unsigned OpNo,
                          SmallVectorImpl<MCFixup> &Fixups,
                          const MCSubtargetInfo &STI) const;

  uint64_t encodeAllocFrame(const MCInst &MI, uint64_t Insn,
                            const MCSubtargetInfo &STI) const;

  uint64_t getLongSlot(const MCInst &MI) const;
};

} // end anonymous namespace

void IA64MCCodeEmitter::encodeInstruction(const MCInst &MI,
                                          SmallVectorImpl<char> &CB,
                                          SmallVectorImpl<MCFixup> &Fixups,
                                          const MCSubtargetInfo &STI) const {
  // An X-unit instruction is two slots, and the L slot comes first.
  if (IA64II::getUnit(MCII.get(MI.getOpcode()).TSFlags) == IA64II::UnitX) {
    uint64_t Long = getLongSlot(MI);
    for (unsigned I = 0; I != IA64::SlotBytes; ++I)
      CB.push_back(static_cast<char>(Long >> (8 * I)));
  }
  // The bundler picks the unit of a pseudo-op that has several forms;
  // otherwise the first form is used.
  unsigned Opcode = IA64::getDefaultOpcode(MI, MCII, *Ctx.getRegisterInfo());
  uint64_t Slot;
  if (Opcode != MI.getOpcode()) {
    MCInst Real = MI;
    Real.setOpcode(Opcode);
    Slot = getBinaryCodeForInstr(Real, Fixups, STI);
  } else {
    Slot = getBinaryCodeForInstr(MI, Fixups, STI);
  }
  // The symbol of ld8.mov has no field to go in.
  if (Opcode == IA64::LD8_MOV && MI.getOperand(2).isExpr())
    Fixups.push_back(MCFixup::create(0, MI.getOperand(2).getExpr(),
                                     IA64::fixup_ia64_ldxmov));
  for (unsigned I = 0; I != IA64::SlotBytes; ++I)
    CB.push_back(static_cast<char>(Slot >> (8 * I)));
}

uint64_t IA64MCCodeEmitter::getLongSlot(const MCInst &MI) const {
  // The L slot holds the immediate bits that the X slot has no room for. A
  // fixup fills in both slots.
  switch (MI.getOpcode()) {
  case IA64::MOVL:
    if (!MI.getOperand(1).isImm())
      return 0;
    return (static_cast<uint64_t>(MI.getOperand(1).getImm()) >> 22) &
           IA64II::SlotMask;
  case IA64::BRL_COND:
  case IA64::BRL_CALL: {
    // Bits 58:20 of the displacement in bundles, above two unused bits.
    unsigned OpNo = MI.getOpcode() == IA64::BRL_CALL ? 1 : 0;
    if (!MI.getOperand(OpNo).isImm())
      return 0;
    uint64_t Bundles = static_cast<uint64_t>(MI.getOperand(OpNo).getImm()) >> 4;
    return ((Bundles >> 20) & maskTrailingOnes<uint64_t>(39)) << 2;
  }
  default:
    // break.x, nop.x and hint.x.
    return (static_cast<uint64_t>(MI.getOperand(0).getImm()) >> 21) &
           IA64II::SlotMask;
  }
}

uint64_t
IA64MCCodeEmitter::getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                                     SmallVectorImpl<MCFixup> &Fixups,
                                     const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<uint64_t>(MO.getImm());
  llvm_unreachable("unhandled operand kind");
}

uint64_t
IA64MCCodeEmitter::getImmMinus1OpValue(const MCInst &MI, unsigned OpNo,
                                       SmallVectorImpl<MCFixup> &Fixups,
                                       const MCSubtargetInfo &STI) const {
  return static_cast<uint64_t>(MI.getOperand(OpNo).getImm() - 1);
}

uint64_t
IA64MCCodeEmitter::getPmpyshrCountOpValue(const MCInst &MI, unsigned OpNo,
                                          SmallVectorImpl<MCFixup> &Fixups,
                                          const MCSubtargetInfo &STI) const {
  switch (MI.getOperand(OpNo).getImm()) {
  case 0:
    return 0;
  case 7:
    return 1;
  case 15:
    return 2;
  case 16:
    return 3;
  }
  llvm_unreachable("invalid pmpyshr2 count");
}

uint64_t IA64MCCodeEmitter::getInc3OpValue(const MCInst &MI, unsigned OpNo,
                                           SmallVectorImpl<MCFixup> &Fixups,
                                           const MCSubtargetInfo &STI) const {
  // A sign and the magnitude: 16, 8, 4 and 1 are 0 to 3.
  int64_t Inc = MI.getOperand(OpNo).getImm();
  uint64_t Sign = Inc < 0 ? 4 : 0;
  switch (Inc < 0 ? -Inc : Inc) {
  case 16:
    return Sign | 0;
  case 8:
    return Sign | 1;
  case 4:
    return Sign | 2;
  case 1:
    return Sign | 3;
  }
  llvm_unreachable("invalid fetchadd increment");
}

uint64_t IA64MCCodeEmitter::encodeAllocFrame(const MCInst &MI, uint64_t Insn,
                                             const MCSubtargetInfo &STI) const {
  // The operands after the destination are the numbers of input, local,
  // output and rotating registers.
  uint64_t Inputs = MI.getOperand(1).getImm();
  uint64_t Locals = MI.getOperand(2).getImm();
  uint64_t Outputs = MI.getOperand(3).getImm();
  uint64_t Rotating = MI.getOperand(4).getImm();
  uint64_t Sol = Inputs + Locals;
  uint64_t Sof = Sol + Outputs;
  assert(Sof <= IA64II::MaxFrameSize && Rotating % 8 == 0 && Rotating <= Sof &&
         "invalid register stack frame");
  return Insn | (Rotating / 8) << 27 | Sol << 20 | Sof << 13;
}

#include "IA64GenMCCodeEmitter.inc"

MCCodeEmitter *llvm::createIA64MCCodeEmitter(const MCInstrInfo &MCII,
                                             MCContext &Ctx) {
  return new IA64MCCodeEmitter(MCII, Ctx);
}
