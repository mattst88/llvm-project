#ifndef LLVM_LIB_TARGET_IA64_IA64SUBTARGET_H
#define LLVM_LIB_TARGET_IA64_IA64SUBTARGET_H

#include "GISel/IA64CallLowering.h"
#include "GISel/IA64LegalizerInfo.h"
#include "GISel/IA64RegisterBankInfo.h"
#include "IA64FrameLowering.h"
#include "IA64ISelLowering.h"
#include "IA64InstrInfo.h"
#include "IA64SelectionDAGInfo.h"
#include "MCTargetDesc/IA64MCTargetDesc.h"
#include "llvm/CodeGen/GlobalISel/InlineAsmLowering.h"
#include "llvm/CodeGen/GlobalISel/InstructionSelector.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <bitset>
#include <memory>

#define GET_SUBTARGETINFO_HEADER
#include "IA64GenSubtargetInfo.inc"

namespace llvm {

class StringRef;
class TargetMachine;

class IA64Subtarget : public IA64GenSubtargetInfo {
  // Registers reserved by the user.
  std::bitset<IA64::NUM_TARGET_REGS> UserReservedRegister;
  bool HasConstantGP = false;
  bool HasStoppedPadding = false;

  IA64InstrInfo InstrInfo;
  IA64TargetLowering TLInfo;
  IA64FrameLowering FrameLowering;
  IA64SelectionDAGInfo TSInfo;
  IA64CallLowering CallLoweringInfo;
  InlineAsmLowering InlineAsmLoweringInfo;
  IA64LegalizerInfo Legalizer;
  IA64RegisterBankInfo RegBankInfo;
  std::unique_ptr<InstructionSelector> InstSelector;

  IA64Subtarget &initializeSubtargetDependencies(StringRef CPU,
                                                 StringRef TuneCPU,
                                                 StringRef FS);

public:
  // TuneCPU selects the scheduling model and the tuning-only decisions; CPU
  // alone decides which instructions may be emitted. An empty TuneCPU tunes
  // for CPU.
  IA64Subtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                StringRef FS, const TargetMachine &TM);

  const IA64InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const IA64RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const IA64TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const IA64FrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

  const CallLowering *getCallLowering() const override {
    return &CallLoweringInfo;
  }
  const InlineAsmLowering *getInlineAsmLowering() const override {
    return &InlineAsmLoweringInfo;
  }
  const LegalizerInfo *getLegalizerInfo() const override { return &Legalizer; }
  const RegisterBankInfo *getRegBankInfo() const override {
    return &RegBankInfo;
  }

  InstructionSelector *getInstructionSelector() const override {
    return InstSelector.get();
  }

  bool hasConstantGP() const { return HasConstantGP; }

  // The processors execute in order and stall at an instruction that needs
  // an earlier result, so instruction order decides how many issue together.
  bool enableMachineScheduler() const override { return true; }
  bool enablePostRAScheduler() const override { return true; }
  // Alias analysis lets the schedulers move a load above a store to memory
  // that the load cannot overlap, which hides most of its latency.
  bool useAA() const override { return true; }
  // Software pipelining overlaps the iterations of a counted loop, which on
  // an in-order machine is the only way they overlap.
  bool enableMachinePipeliner() const override;
  bool useDFAforSMS() const override { return false; }
  // The window scheduler, which the pipeliner falls back on, schedules with
  // the target's own machine scheduler, and IA64 uses the generic one.
  bool enableWindowScheduler() const override { return false; }

  bool isRegisterReservedByUser(Register Reg) const override {
    assert(Reg.id() < IA64::NUM_TARGET_REGS && "not a physical register");
    return UserReservedRegister[Reg.id()];
  }

  // Automatically generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_IA64_IA64SUBTARGET_H
